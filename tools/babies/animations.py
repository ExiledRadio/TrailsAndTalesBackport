"""Writes the 26.1 baby animations (CamelBabyAnimations, BabyArmadilloAnimations) from 26.3's keyframes.

The keyframes are Mojang's: 26.3's net.minecraft.client.animation.definitions.CamelBabyAnimation and
BabyArmadilloAnimation, decompiled from the (unobfuscated) 26.3 client jar into G:/MCDownloads/gd-mech-decomp/out.
Each definition becomes a call chain on the stream's own KeyframeAnimation class, every number as 26.3 has it.
Also checks that 26.3's adult SnifferAnimation is still 1.20's (the snifflet draws the adult animations).

    python -I tools/babies/animations.py [decompiled source root]
"""
import os
import re
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "G:/MCDownloads/gd-mech-decomp/out"
DEFS = os.path.join(SRC, "net", "minecraft", "client", "animation", "definitions")
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
JAVA = os.path.join(ROOT, "src", "main", "java", "com", "exiledradio", "trailsandtalesbackport")

NUM = r"(-?[0-9.]+(?:E-?[0-9]+)?)F?"
JOBS = [
    # (26.3 class, stream package, our class)
    ("CamelBabyAnimation", "camel", "CamelBabyAnimations"),
    ("BabyArmadilloAnimation", "armadillo", "BabyArmadilloAnimations"),
]


def f(n):
    return n if any(c in n for c in ".E") else n + ".0"


def convert(text):
    """@return {name: java chain} for every AnimationDefinition in a decompiled definitions class"""
    defs = re.split(r"public static final AnimationDefinition ", text)[1:]
    out = {}
    for d in defs:
        name = d.split(" ", 1)[0]
        length = re.search(r"Builder\.withLength\(" + NUM + r"\)", d).group(1)
        looping = ".looping()" in d.split(".addAnimation", 1)[0]
        lines = ["    static final KeyframeAnimation %s = KeyframeAnimation.withLength(%sF)%s" % (
            name, f(length), "\n            .looping()" if looping else "")]
        for chunk in d.split(".addAnimation(")[1:]:
            ch = re.match(r'\s*"(\w+)",\s*new AnimationChannel\(\s*(?:AnimationChannel\.)?Targets\.(\w+),', chunk)
            bone, target = ch.groups()
            body = chunk[ch.end():]
            keys = []
            for k in re.finditer(r"new Keyframe\(" + NUM + r",\s*KeyframeAnimations\.(\w+)\(" + NUM + r",\s*" + NUM
                                 + r",\s*" + NUM + r"\),\s*(?:AnimationChannel\.)?Interpolations\.(\w+)\)", body):
                t, fn, x, y, z, interp = k.groups()
                keys.append("key(%sF, KeyframeAnimation.%s(%sF, %sF, %sF), %s)" % (
                    f(t), {"posVec": "pos", "degreeVec": "deg", "scaleVec": "scale"}[fn], f(x), f(y), f(z),
                    "KeyframeAnimation.LINEAR" if interp == "LINEAR" else "KeyframeAnimation.CATMULLROM"))
            if len(keys) != body.count("new Keyframe("):
                raise ValueError("%s/%s: parsed %d of %d keyframes" % (name, bone, len(keys), body.count("new Keyframe(")))
            lines.append("            .add(\"%s\", KeyframeAnimation.%s,\n                    %s)" % (
                bone, target, ",\n                    ".join(keys)))
        if len(lines) - 1 != d.count(".addAnimation("):
            raise ValueError("%s: parsed %d of %d channels" % (name, len(lines) - 1, d.count(".addAnimation(")))
        out[name] = "\n".join(lines) + ";"
    return out


def main():
    for src, pkg, cls in JOBS:
        anims = convert(open(os.path.join(DEFS, src + ".java"), encoding="utf-8").read())
        java = """package com.exiledradio.trailsandtalesbackport.%s.client;

import static com.exiledradio.trailsandtalesbackport.%s.client.KeyframeAnimation.key;

/**
 * 26.1's baby animations ({@code %s}, as 26.3 has them), keyframe for keyframe. Generated by
 * {@code tools/babies/animations.py}; do not edit by hand.
 */
final class %s {

    private %s() {
    }

%s
}
""" % (pkg, pkg, src, cls, cls, "\n\n".join(anims.values()))
        path = os.path.join(JAVA, pkg, "client", cls + ".java")
        with open(path, "w", encoding="utf-8", newline="\n") as out:
            out.write(java)
        print("%s: %d animations" % (cls, len(anims)))
    # The snifflet draws 26.3's adult animations: check they are still the stream's (1.20's).
    new = convert(open(os.path.join(DEFS, "SnifferAnimation.java"), encoding="utf-8").read())
    ours = open(os.path.join(JAVA, "sniffer", "client", "SnifferAnimations.java"), encoding="utf-8").read()
    for name, chain in new.items():
        if name == "BABY_TRANSFORM":
            continue
        norm = lambda s: re.sub(r"\s+", "", s)
        if norm(chain) not in norm(ours):
            print("SnifferAnimation.%s differs from 1.20's" % name)
    print("sniffer checked: %d animations" % len(new))


if __name__ == "__main__":
    main()
