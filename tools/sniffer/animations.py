"""Writes sniffer/client/SnifferAnimations.java from 1.20's SnifferAnimation keyframes.

The keyframes are Mojang's (1.20.1's net.minecraft.client.animation.definitions.SnifferAnimation, decompiled
from the client jar with Mojang's names into G:/MCDownloads/tt-sniffer-decomp); this turns each definition
into a call chain on our own KeyframeAnimation class, keeping every number as 1.20 has it.

    python tools/sniffer/animations.py [path to SnifferAnimation.java]
"""
import os
import re
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else \
    "G:/MCDownloads/tt-sniffer-decomp/out/net/minecraft/client/animation/definitions/SnifferAnimation.java"
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "src", "main", "java", "com", "exiledradio", "trailsandtalesbackport", "sniffer", "client",
                   "SnifferAnimations.java")

text = open(SRC, encoding="utf-8").read()
NUM = r"(-?[0-9.]+(?:E-?[0-9]+)?)F?"
defs = re.split(r"public static final AnimationDefinition ", text)[1:]
out = []
for d in defs:
    name = d.split(" ", 1)[0]
    length = re.search(r"Builder\.withLength\(" + NUM + r"\)", d).group(1)
    looping = ".looping()" in d.split(".addAnimation", 1)[0]
    lines = ["    static final KeyframeAnimation %s = KeyframeAnimation.withLength(%sF)%s" % (
        name, length, "\n            .looping()" if looping else "")]
    for ch in re.finditer(r"\.addAnimation\(\s*\"(\w+)\",\s*new AnimationChannel\(\s*Targets\.(\w+),\s*new Keyframe\[\]\{(.*?)\}\s*\)\s*\)", d, re.S):
        bone, target, body = ch.groups()
        keys = []
        for k in re.finditer(r"new Keyframe\(" + NUM + r",\s*KeyframeAnimations\.(\w+)\(" + NUM + r",\s*" + NUM + r",\s*" + NUM
                             + r"\),\s*Interpolations\.(\w+)\)", body):
            t, fn, x, y, z, interp = k.groups()
            keys.append("key(%sF, KeyframeAnimation.%s(%sF, %sF, %sF), %s)" % (
                t, {"posVec": "pos", "degreeVec": "deg", "scaleVec": "scale"}[fn], x, y, z,
                "KeyframeAnimation.LINEAR" if interp == "LINEAR" else "KeyframeAnimation.CATMULLROM"))
        if len(keys) != body.count("new Keyframe("):
            raise ValueError("%s/%s: parsed %d of %d keyframes" % (name, bone, len(keys), body.count("new Keyframe(")))
        lines.append("            .add(\"%s\", KeyframeAnimation.%s,\n                    %s)" % (
            bone, target, ",\n                    ".join(keys)))
    if len(lines) - 1 != d.count(".addAnimation("):
        raise ValueError("%s: parsed %d of %d channels" % (name, len(lines) - 1, d.count(".addAnimation(")))
    out.append("\n".join(lines) + ";")

java = """package com.exiledradio.trailsandtalesbackport.sniffer.client;

import static com.exiledradio.trailsandtalesbackport.sniffer.client.KeyframeAnimation.key;

/**
 * 1.20's sniffer animations ({@code SnifferAnimation}), keyframe for keyframe. Generated by
 * {@code tools/sniffer/animations.py}; do not edit by hand.
 */
final class SnifferAnimations {

    private SnifferAnimations() {
    }

%s
}
""" % "\n\n".join(out)
os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write(java)
print("wrote %d animations" % len(out))
